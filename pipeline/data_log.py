"""Write DATA_LOG.md from the per-source status records in data/processed/_status/."""
from __future__ import annotations

import json
from datetime import datetime, timezone

from .common import PILOT, ROOT, STATUS_DIR, run_source

SOURCE, TITLE, TIER = "datalog", "DATA_LOG.md", "MUST"
ORDER = ["fields", "nasa_power", "gpm_imerg", "smap", "ssurgo", "usda_cdl", "landsat", "openet", "srtm",
         "modis", "gridmet", "usgs_nwis", "indicators", "overlays"]
BADGE = {"ok": "OK", "partial": "PARTIAL", "failed": "FAILED - ACTION NEEDED", "skipped": "SKIPPED"}

NOT_USED = [
    ("Google Earth Engine", "OPTIONAL route",
     "Not used. `earthengine authenticate` had not been run on the build machine, so Landsat was read from "
     "Microsoft Planetary Computer instead (the same Landsat Collection 2 Level-2 scenes). Nothing in the "
     "app depends on Earth Engine. `python -m pipeline.check_access` reports whether it is ready."),
    ("ECOSTRESS (land-surface temperature, ET)", "SKIP",
     "Skipped. Irregular overpass times and revisit (it rides on the ISS), frequent cloud gaps and heavier "
     "swath preprocessing make it a poor fit for a monthly field record; OpenET already supplies field-scale "
     "ET from Landsat thermal data. A good add-on for mapping within-field heat hotspots."),
    ("GRACE / GRACE-FO (water storage)", "SKIP",
     "Skipped for field decisions. Its footprint is roughly 300 km, hundreds of times larger than the whole "
     "valley, so it cannot say anything about one field or one basin this small. The long-term water trend "
     "in the app comes instead from USGS wells inside the valley, which measure the aquifer directly."),
    ("GEDI (canopy height, biomass)", "SKIP",
     "Skipped. A forest-structure lidar with sparse footprints; not meaningful over hay fields."),
    ("PRISM", "OPTIONAL",
     "Not fetched separately. gridMET, which is used to correct NASA POWER, already carries PRISM's "
     "station-and-terrain climatology at 4 km with daily values, which is what frost dates need."),
    ("NLDAS / GLDAS", "OPTIONAL",
     "Not fetched. They sit behind the same GES DISC data-use agreement that currently blocks IMERG (see "
     "above). Once that agreement is accepted they could add a longer modelled soil-moisture record."),
    ("ERA5", "OPTIONAL",
     "Not fetched. Needs a Copernicus Climate Data Store account and key, which were not provided, and at "
     "~31 km it would add little beyond NASA POWER."),
    ("Sentinel-2", "OPTIONAL",
     "Not fetched. Landsat 8/9 already gives about 300 clear observations per field for 2018-2025; "
     "Sentinel-2 would sharpen within-field detail but was not needed for field-level monthly indicators."),
    ("NLCD, NAIP, LANDFIRE", "OPTIONAL",
     "Not fetched. Land cover around the fields is already clear from the CDL (shrubland), and 1 m NAIP "
     "imagery is a large download whose main use here would be checking field outlines by eye."),
    ("NASS QuickStats, AMS Market News", "OPTIONAL",
     "Not fetched. QuickStats needs an API key that was not provided; both are county, state or market "
     "level, not field level. Their absence is why the forage/income score is marked low confidence and "
     "why 'local prices and buyers' appears in every information-gap list."),
    ("FAO GAEZ, CoCoRaHS, Ag Data Commons", "OPTIONAL",
     "Not fetched. GAEZ suitability layers are too coarse for one valley; CoCoRaHS has few observers in "
     "this part of Nevada; Ag Data Commons is a catalogue rather than a single dataset."),
]


def main() -> None:
    recs = {}
    for p in STATUS_DIR.glob("*.json"):
        r = json.loads(p.read_text(encoding="utf-8"))
        recs[r["source"]] = r
    lines = [
        "# DATA_LOG", "",
        f"Pilot region: **{PILOT['name']}**, box {PILOT['bbox']} (west, south, east, north).",
        f"Generated by `python -m pipeline.data_log` on "
        f"{datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC from the status files the pipeline writes.", "",
        "No demo, sample or simulated data is used anywhere: every value in `data/processed` was fetched "
        "from the source named here. A source that could not be fetched is listed as FAILED with the exact "
        "step needed, and the app shows it as missing.", "",
        "## Summary", "",
        "| Source | Tier | Status | Date range | Resolution |", "| :-- | :-- | :-- | :-- | :-- |",
    ]
    ordered = [recs[k] for k in ORDER if k in recs] + [r for k, r in recs.items() if k not in ORDER and k != SOURCE]
    for r in ordered:
        lines.append(f"| {r['title']} | {r['tier']} | **{BADGE.get(r['status'], r['status'])}** | "
                     f"{r.get('date_range') or '-'} | {r.get('resolution') or '-'} |")
    lines += ["", "## Details", ""]
    for r in ordered:
        lines += [f"### {r['title']}", "",
                  f"- **Status:** {BADGE.get(r['status'], r['status'])}: {r.get('message', '')}"]
        if r.get("action_needed"):
            lines.append(f"- **Action needed:** {r['action_needed']}")
        for label, key in (("What was fetched", "fetched"), ("Resolution", "resolution"),
                           ("Date range", "date_range"), ("Access route", "access"),
                           ("Credit / licence", "credit"), ("Caveats", "notes")):
            if r.get(key):
                lines.append(f"- **{label}:** {r[key]}")
        if r.get("outputs"):
            lines.append("- **Outputs:** " + ", ".join(f"`data/processed/{o}`" for o in r["outputs"]))
        checks = (r.get("sanity") or {}).get("checks") or []
        if checks:
            lines += ["- **Sanity checks:**", "", "  | Variable | n | min | mean | max | expected | result |",
                      "  | :-- | --: | --: | --: | --: | :-- | :-- |"]
            for c in checks:
                lines.append(f"  | {c['variable']} | {c['n']} | {c.get('min', '-')} | {c.get('mean', '-')} | "
                             f"{c.get('max', '-')} | {c['expected_range'][0]} to {c['expected_range'][1]} | "
                             f"{'pass' if c['passed'] else 'CHECK'}{' (all NaN)' if c.get('all_nan') else ''} |")
            lines.append("")
        extra = {k: v for k, v in (r.get("sanity") or {}).items() if k != "checks"}
        if extra:
            lines.append(f"- **Other checks:** `{json.dumps(extra)[:900]}`")
        lines.append(f"- **Demo data:** {'YES' if r.get('is_demo_data') else 'no'}")
        lines.append("")
    lines += ["## Listed in the challenge resources but not used", "",
              "| Source | Tier in the plan | Why |", "| :-- | :-- | :-- |"]
    lines += [f"| {n} | {t} | {w} |" for n, t, w in NOT_USED]
    lines.append("")
    (ROOT / "DATA_LOG.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"[OK ] DATA_LOG.md written ({len(ordered)} sources)")


if __name__ == "__main__":
    run_source(SOURCE, TITLE, TIER, main)
